type NavItem = { href: string; label: string };

function addFollowNav(nav: readonly NavItem[], label: string): NavItem[] {
  const items = nav.map((item) => ({ href: item.href, label: item.label }));
  if (items.some((item) => item.href === "#follow")) return items;
  const item = { href: "#follow", label };
  const at = items.findIndex((n) => n.href === "#play");
  if (at < 0) return [...items, item];
  return [...items.slice(0, at), item, ...items.slice(at)];
}

function withFollow<
  T extends {
    anshen: { nav: readonly NavItem[] };
    jieyu: { nav: readonly NavItem[] };
    anmei: { nav: readonly NavItem[] };
    yali: { nav: readonly NavItem[] };
  },
>(
  base: T,
  lang: Lang,
) {
  const pack = FOLLOW[lang];
  const navLabel = lang === "en" ? "Follow" : lang === "cmn" ? "跟著做" : "跟住做";
  return {
    ...base,
    anshen: { ...base.anshen, nav: addFollowNav(base.anshen.nav, navLabel), follow: pack.anshen },
    jieyu: { ...base.jieyu, nav: addFollowNav(base.jieyu.nav, navLabel), follow: pack.jieyu },
    anmei: { ...base.anmei, nav: addFollowNav(base.anmei.nav, navLabel), follow: pack.anmei },
    yali: { ...base.yali, nav: addFollowNav(base.yali.nav, navLabel), follow: pack.yali },
  };
}

const yueCopy = withFollow(YUE, "yue");

export type Copy = typeof yueCopy;

function merge(base: unknown, over: unknown): unknown {
  if (over === undefined) return base;
  if (typeof base !== "object" || base === null || Array.isArray(base) || typeof base === "function") {
    return over;
  }
  if (typeof over !== "object" || over === null || Array.isArray(over)) return over;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const k of Object.keys(over as object)) {
    out[k] = merge((base as Record<string, unknown>)[k], (over as Record<string, unknown>)[k]);
  }
  return out;
}

/**
 * 舒壓 shares approved safety copy instead of re-wording it: the footer note is 安神's in each
 * language, and the crisis sentence is the FAQ's (yue/cmn). EN has no FAQ, so its crisis sentence
 * lives in copy-extra.ts as a translation (flagged for clinician approval).
 */
function withYaliShared(copy: Copy, lang: Lang): Copy {
  return {
    ...copy,
    yali: {
      ...copy.yali,
      footerNote: copy.anshen.footerNote,
      careCrisis: lang === "en" ? copy.yali.careCrisis : crisisLine(lang),
    },
  };
}

